import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { parseEnv } from 'node:util';
import { chromium } from 'playwright';
import { Wallet, JsonRpcProvider, Interface, keccak256 } from 'ethers';
import artifact from '../../../contracts/abi/OwnershipRegistry.json' with { type: 'json' };

const required = name => { if (!process.env[name]) throw new Error(`Set ${name}`); return process.env[name]; };
const cardId = required('LIVE_TEST_CARD_ID');
const keyFile = required('LIVE_TEST_KEYSTORE');
const passwordFile = required('LIVE_TEST_PASSWORD_FILE');
const stateFile = required('LIVE_TEST_TRANSACTION_FILE');
const base = process.env.LIVE_TEST_UI_URL ?? 'https://shomei-kun-integration.dptr.workers.dev/ui/';
const env = parseEnv(await readFile('../../apps/web/.env.local', 'utf8'));
const chainId = 2017072401;
assert.equal(Number(env.CHAIN_ID), chainId);
const provider = new JsonRpcProvider(env.CURVEGRID_PUBLIC_WEB3_RPC_URL, undefined, { cacheTimeout: -1 });
const wallet = (await Wallet.fromEncryptedJson(await readFile(keyFile, 'utf8'), (await readFile(passwordFile, 'utf8')).trim())).connect(provider);
const nickname = 'おじいちゃんコンビニ';
const iface = new Interface(artifact.abi);
const api = new URL(base).origin;
const expectedData = iface.encodeFunctionData('register', [cardId, nickname]);
let sends = 0;
const browser = await chromium.launch();
const output = resolve('artifacts/live-chain');
await mkdir(output, { recursive: true });
const errors = [];
try {
  assert.equal((await provider.getNetwork()).chainId, BigInt(chainId));
  const cardResponse = await fetch(`${api}/api/v1/cards/${cardId}`);
  assert.equal(cardResponse.status, 200);
  const initial = await cardResponse.json();
  assert.equal(initial.meta.mode, 'live');
  assert.equal(initial.data.status, 'unregistered', 'Use a newly issued, unregistered test card');
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, locale: 'ja-JP', isMobile: true, hasTouch: true });
  const page = await context.newPage();
  page.setDefaultTimeout(45000);
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text().replace(/https?:\/\/\S+/g, '[url]')); });
  await page.exposeFunction('testWalletRequest', async ({ method, params }) => {
    if (['eth_accounts', 'eth_requestAccounts'].includes(method)) return [wallet.address];
    if (method === 'eth_chainId') return `0x${chainId.toString(16)}`;
    assert.equal(method, 'eth_sendTransaction');
    sends++;
    assert.equal(sends, 1, 'No duplicate wallet send');
    const tx = params[0];
    assert.equal(tx.from.toLowerCase(), wallet.address.toLowerCase());
    assert.equal(tx.to.toLowerCase(), env.REGISTRY_ADDRESS.toLowerCase());
    assert.equal(BigInt(tx.chainId), BigInt(chainId));
    assert.equal(BigInt(tx.value), 0n);
    assert.equal(tx.data, expectedData);
    const populated = await wallet.populateTransaction({ to: tx.to, data: tx.data, value: 0, chainId });
    const raw = await wallet.signTransaction(populated);
    const hash = keccak256(raw);
    await writeFile(stateFile, JSON.stringify({ hash, raw, cardId }), { flag: 'wx', mode: 0o600 });
    await provider.broadcastTransaction(raw);
    return hash;
  });
  await page.addInitScript(() => {
    window.ethereum = { isMetaMask: true, on() {}, removeListener() {}, request(args) { return window.testWalletRequest(args); } };
  });
  await page.goto(`${base}?cardId=${cardId}`);
  await page.locator('[data-action="start-register"]').click();
  await page.locator('#nickname').fill(nickname);
  await page.locator('[data-action="connect"]').click();
  await page.locator('[data-action="confirm"]').click();
  await page.locator('#consent').check();
  await page.screenshot({ path: `${output}/390-review.png`, fullPage: true });
  await page.locator('[data-action="register-reviewed"]').click();
  await page.locator('.result-page').waitFor({ timeout: 90000 });
  assert.match(await page.locator('.record-table').innerText(), new RegExp(wallet.address, 'i'));
  await page.screenshot({ path: `${output}/390-confirmed.png`, fullPage: true });
  await page.reload();
  await page.locator('.result-page').waitFor();
  assert.equal(sends, 1);
  const reader = await browser.newContext({ viewport: { width: 320, height: 720 }, locale: 'en-US', isMobile: true, hasTouch: true });
  const publicPage = await reader.newPage();
  await publicPage.goto(`${base}?cardId=${cardId}`);
  await publicPage.locator('.result-page').waitFor();
  assert.match(await publicPage.locator('.record-table').innerText(), new RegExp(wallet.address, 'i'));
  assert.equal(await publicPage.locator('[data-action="start-register"]').count(), 0);
  assert(await publicPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await publicPage.screenshot({ path: `${output}/320-public-en.png`, fullPage: true });
  const { hash } = JSON.parse(await readFile(stateFile, 'utf8'));
  const transaction = await (await fetch(`${api}/api/v1/cards/${cardId}/transactions/${hash}`)).json();
  assert.equal(transaction.data.status, 'confirmed');
  assert.deepEqual(errors, []);
  await writeFile(`${output}/results.json`, JSON.stringify({ type: 'Browser with locally signing test provider; not physical MetaMask', base, cardId, address: wallet.address, transactionHash: hash, walletSends: sends, reloadVerified: true, publicReaderVerified: true, errors, transaction }, null, 2));
  console.log(JSON.stringify({ cardId, address: wallet.address, transactionHash: hash, walletSends: sends, confirmed: true }));
} finally { await browser.close(); provider.destroy(); }
